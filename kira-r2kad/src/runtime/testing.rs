use std::{
    cell::RefCell,
    time::{
        Duration,
        Instant,
    },
};

use crate::{
    Output,
    domain::{
        ForwardingTablesUpdate,
        ProtocolMessage,
        UnderlayNeighborDestination,
    },
    runtime::UseCaseRuntime,
    use_cases::{
        BroadcastableUseCaseEvent,
        TimerId,
        UseCaseEvent,
    },
};

#[derive(Debug, Default)]
pub struct TestingUseCaseRuntime {
    // NOTE: we *always* generate the same id (unless `unique_timer_ids` is set)
    pub timer_id: usize,
    /// Return a distinct id (`timer_id + n`) for the n-th registered timer instead of
    /// always `timer_id`. Needed for use cases that tell their timers apart.
    pub unique_timer_ids: bool,
    pub current_time: RefCell<Option<Instant>>,

    timers: RefCell<usize>,
    registered_timers: RefCell<Vec<(TimerId, Duration)>>,
    removed_timers: RefCell<Vec<TimerId>>,

    output: RefCell<Vec<Output>>,
    broadcast: RefCell<Vec<UseCaseEvent>>,
}

impl TestingUseCaseRuntime {
    /// Runtime that returns a distinct id for every registered timer.
    pub fn with_unique_timer_ids() -> Self {
        Self {
            unique_timer_ids: true,
            ..Default::default()
        }
    }

    /// Returns the number of registered timers.
    ///
    /// You can fire *all* registered timers by
    /// [handling](crate::use_cases::EventHandler::handle_event)
    /// the event returned by [timer](Self::timer).
    pub fn timers(&self) -> usize {
        *self.timers.borrow()
    }

    /// [Timer event](UseCaseEvent) to fire *all* registered timers.
    ///
    /// Use the [EventHandler::handle_event](crate::use_cases::EventHandler::handle_event)
    /// of a use case to handle the event.
    pub fn timer(&self) -> UseCaseEvent {
        UseCaseEvent::Timer(self.timer_id.into())
    }

    /// Get all accumulated [Output] events generated by the use cases.
    pub fn output(&self) -> impl Iterator<Item = Output> + '_ {
        self.output
            .borrow_mut()
            .drain(..)
            .collect::<Vec<_>>()
            .into_iter()
    }

    /// Get all accumulated [BroadcastableUseCaseEvent] events generated by the use cases.
    pub fn broadcast(&self) -> impl Iterator<Item = UseCaseEvent> + '_ {
        self.broadcast
            .borrow_mut()
            .drain(..)
            .collect::<Vec<_>>()
            .into_iter()
    }

    pub fn set_current_time(&self, now: Instant) {
        self.current_time.borrow_mut().replace(now);
    }

    /// All registered timers with their (possibly randomized) duration, in registration order.
    pub fn registered_timers(&self) -> Vec<(TimerId, Duration)> {
        self.registered_timers.borrow().clone()
    }

    /// All timers passed to [remove_timer](UseCaseRuntime::remove_timer), in call order.
    pub fn removed_timers(&self) -> Vec<TimerId> {
        self.removed_timers.borrow().clone()
    }

    fn next_timer_id(&self, duration: Duration) -> TimerId {
        let mut timers = self.timers.borrow_mut();
        *timers += 1;
        let timer_id: TimerId = if self.unique_timer_ids {
            (self.timer_id + *timers).into()
        } else {
            self.timer_id.into()
        };
        self.registered_timers
            .borrow_mut()
            .push((timer_id, duration));
        timer_id
    }
}

impl UseCaseRuntime for TestingUseCaseRuntime {
    fn register_timer(&self, duration: Duration) -> TimerId {
        self.next_timer_id(duration)
    }

    fn remove_timer(&self, timer_id: TimerId) {
        // the timer is only recorded, it may still be fired by the test
        self.removed_timers.borrow_mut().push(timer_id);
    }

    fn register_periodic_timer(&self, duration: Duration) -> TimerId {
        self.next_timer_id(duration)
    }

    fn current_time(&self) -> Instant {
        self.current_time.borrow().unwrap_or_else(Instant::now)
    }

    fn send_message_via<P: Into<ProtocolMessage>>(
        &self,
        protocol_message: P,
        destination: UnderlayNeighborDestination,
    ) {
        self.output.borrow_mut().push(Output::SendProtocolMessage(
            protocol_message.into(),
            destination,
        ));
    }

    fn update_fwd_tables<U: Into<ForwardingTablesUpdate>>(&self, update: U) {
        self.output
            .borrow_mut()
            .push(Output::UpdateForwardingTables(update.into()));
    }

    fn broadcast_event<B: Into<BroadcastableUseCaseEvent>>(&self, event: B) {
        self.broadcast.borrow_mut().push(event.into().into());
    }

    fn timer_remaining_duration(&self, timer: &TimerId) -> Option<Duration> {
        if timer == &self.timer_id.into() {
            Some(Duration::ZERO)
        } else {
            None
        }
    }
}
